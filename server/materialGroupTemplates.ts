export function inferMaterialGroupClass(
  matkl: string,
  description: string,
  characteristics: Record<string, string | number | boolean> = {}
): { matkl: string; className: string } | undefined {
  const text = `${description} ${Object.values(characteristics).join(' ')}`.toLowerCase();
  const groupCode = matkl.toUpperCase();

  if (['UN-LVH', '04-LV'].includes(groupCode)) {
    if (/wheel loader|excavator|grader|bulldozer|roller|compactor|crane/.test(text)) {
      return {
        matkl: '01-HE',
        className: /excavator/.test(text)
          ? 'CLS_HE_EXCAVATOR'
          : /bulldozer/.test(text)
            ? 'CLS_HE_DOZER'
            : 'CLS_HE_GRADER',
      };
    }
    return {
      matkl: '04-LV',
      className: /bemo|minibus|fortuner|passenger|mpv|suv/.test(text)
        ? 'CLS_LV_PASSENGER'
        : 'CLS_LV_DOUBLECAB',
    };
  }

  if (/seamless line pipe|gate valve|valve 4|pipe 8/.test(text)) {
    return { matkl: '14-MAT', className: 'CLS_MAT_PIPE' };
  }
  if (/barite|bentonite|drilling mud|chemical additive/.test(text)) {
    return { matkl: '08-CHM', className: 'CLS_CHM_MAINT' };
  }
  if (/calibration gas cylinder|gas cylinder/.test(text)) {
    return { matkl: '08-CHM', className: 'CLS_CHM_MAINT' };
  }
  if (/brake pad|suspensi|tie rod/.test(text)) {
    return { matkl: '06-SP', className: 'CLS_SP_GENERAL' };
  }

  return LEGACY_MATERIAL_GROUP_MAPPING[groupCode];
}
