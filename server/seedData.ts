export function createInitialMultiTenantDatabase(): MultiTenantDatabase {
  const db: MultiTenantDatabase = {
    schemaVersion: 28,
    activeTenantId: TENANT_COMPANIES[0].tenantId,
    tenantCompanies: structuredClone(TENANT_COMPANIES),
    workspaces: {
      'tenant-oilgas': buildOilGasWorkspace(),
      'tenant-tools-ppe': buildToolsPpeWorkspace(),
      'tenant-mt': buildMtCalibrationWorkspace(),
      'tenant-workshop': buildWorkshopWorkspace(),
      'tenant-unitparts': buildUnitPartsWorkspace(),
    },
    corporateSearchDictionary: createDefaultMaterialSearchDictionary(),
  };

  for (const company of db.tenantCompanies) {
    const ws = db.workspaces[company.tenantId];
    if (ws) {
      ws.materialGroups = createStandardizedMaterialGroups(company.coreBusinessType);
      ws.classificationClasses = createMaterialClassificationClasses(ws.materialGroups);
      const groupClasses = new Map(ws.materialGroups.map((group) => [group.matkl, group.defaultBklas]));
      for (const material of ws.materials) {
        const mapping = inferMaterialGroupClass(
          material.mara.matkl,
          material.mara.maktx,
          material.characteristics
        );
        if (mapping) {
          material.mara.matkl = mapping.matkl;
          material.classificationClass = mapping.className;
        } else {
          const currentGroup = ws.materialGroups.find((group) => group.matkl === material.mara.matkl);
          material.classificationClass ||= currentGroup?.classNames[0];
        }
        const defaultBklas = groupClasses.get(material.mara.matkl);
        if (!defaultBklas) continue;
        for (const valuation of Object.values(material.mbew)) {
          valuation.bklas = defaultBklas;
          for (const split of Object.values(valuation.splitValuations || {})) {
            if (split) split.bklas = defaultBklas;
          }
        }
      }
    }
  }

  const corporateMaterials = new Map<string, MaterialMasterRecord>();
  for (const company of db.tenantCompanies) {
    for (const material of db.workspaces[company.tenantId]?.materials || []) {
      if (!corporateMaterials.has(material.mara.matnr)) {
        corporateMaterials.set(material.mara.matnr, structuredClone(material));
      }
    }
  }

  db.corporateMaraMaterials = Array.from(corporateMaterials.values()).map((material) => {
    material.mara.mbrsh = 'M';
    material.mara.mtart = 'HAWA';
    const bklas = material.mara.matkl.startsWith('SV-') ? '3200' : '3100';
    for (const valuation of Object.values(material.mbew)) {
      valuation.bklas = bklas;
      for (const split of Object.values(valuation.splitValuations || {})) {
        if (split) split.bklas = bklas;
      }
    }
    return material;
  });
  db.schemaVersion = 22;
  return db;
}
