export function createMaterialClassificationClasses(
  groups: MaterialGroupDefinition[]
): MaterialClassificationClass[] {
  const classes = structuredClone(MATERIAL_CLASS_TEMPLATES);
  for (const group of groups) {
    const mapping = LEGACY_MATERIAL_GROUP_MAPPING[group.matkl];
    const groupTemplate = MATERIAL_GROUP_TEMPLATES.find((item) => item.matkl === group.matkl);
    group.classNames = groupTemplate?.classNames || (mapping ? [mapping.className] : group.classNames || []);
    group.classificationClass = group.classNames[0];
    group.characteristics = [];
  }
  return classes;
}

